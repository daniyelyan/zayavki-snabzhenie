# -*- coding: utf-8 -*-
import os
from openpyxl import Workbook
from openpyxl.styles import Font, Alignment, Border, Side
from openpyxl.utils import get_column_letter

OUT_DIR = r"reports/Заявки готовые"
os.makedirs(OUT_DIR, exist_ok=True)

COLS = ["№ п/п", "Раздел", "Наименование", "Марка", "Ед. изм.", "Кол-во", "Область применения", "Примечание"]
N_COLS = len(COLS)

thin = Side(style="thin", color="000000")
border = Border(left=thin, right=thin, top=thin, bottom=thin)


def build_workbook(header_text, rows, problems, filename):
    wb = Workbook()
    ws = wb.active
    ws.title = "Заявка"

    ws.cell(row=1, column=1, value=header_text)
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=N_COLS)
    top = ws.cell(row=1, column=1)
    top.font = Font(bold=True, size=12)
    top.alignment = Alignment(horizontal="left", vertical="center")

    # row 2 empty

    header_row = 3
    for j, title in enumerate(COLS, start=1):
        c = ws.cell(row=header_row, column=j, value=title)
        c.font = Font(bold=True)
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = border

    r = header_row + 1
    for row in rows:
        # row: (num, razdel, naimenovanie, marka, edizm, kolvo, oblast, primechanie)
        for j, val in enumerate(row, start=1):
            c = ws.cell(row=r, column=j, value=val)
            c.border = border
            c.alignment = Alignment(vertical="center", wrap_text=True, horizontal=("center" if j in (1, 5, 6) else "left"))
        r += 1

    widths = [6, 16, 46, 18, 10, 10, 20, 24]
    for j, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(j)].width = w

    ws.freeze_panes = ws.cell(row=header_row + 1, column=1)

    # Problems sheet
    ws2 = wb.create_sheet("Проблемы")
    p_cols = ["№ п/п поз.", "Стр.", "Что не разобрано / что сделал", "Что предполагаю"]
    for j, title in enumerate(p_cols, start=1):
        c = ws2.cell(row=1, column=j, value=title)
        c.font = Font(bold=True)
        c.border = border
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

    if not problems:
        ws2.cell(row=2, column=1, value="—")
        ws2.cell(row=2, column=3, value="замечаний нет")
        for j in range(1, 5):
            ws2.cell(row=2, column=j).border = border
    else:
        r = 2
        for prow in problems:
            for j, val in enumerate(prow, start=1):
                c = ws2.cell(row=r, column=j, value=val)
                c.border = border
                c.alignment = Alignment(vertical="top", wrap_text=True)
            r += 1

    p_widths = [10, 6, 60, 40]
    for j, w in enumerate(p_widths, start=1):
        ws2.column_dimensions[get_column_letter(j)].width = w

    path = os.path.join(OUT_DIR, filename)
    wb.save(path)
    print("saved:", path)


